-- Ejecutar una vez con el usuario de la aplicacion (SQL Developer Web o SQL Developer).

CREATE TABLE pet (
    id     NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    name   VARCHAR2(50) NOT NULL,
    breed  VARCHAR2(50) NOT NULL,
    age    NUMBER(2)    NOT NULL CHECK (age BETWEEN 0 AND 40)
);

