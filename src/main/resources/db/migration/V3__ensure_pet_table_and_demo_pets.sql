DECLARE
    pet_table_count NUMBER;
BEGIN
    SELECT COUNT(*)
      INTO pet_table_count
      FROM USER_TABLES
     WHERE TABLE_NAME = 'PET';

    IF pet_table_count = 0 THEN
        EXECUTE IMMEDIATE 'CREATE TABLE PET (
            ID NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
            NAME VARCHAR2(50) NOT NULL,
            BREED VARCHAR2(50) NOT NULL,
            AGE NUMBER(2) NOT NULL CHECK (AGE BETWEEN 0 AND 40)
        )';
    END IF;
END;
/

MERGE INTO PET target
USING (
    SELECT 'Firulais' AS name, 'Labrador' AS breed, 3 AS age FROM dual
    UNION ALL SELECT 'Michi', 'Siames', 2 FROM dual
    UNION ALL SELECT 'Rocky', 'Bulldog Frances', 5 FROM dual
    UNION ALL SELECT 'Luna', 'Border Collie', 1 FROM dual
) source
ON (
    target.NAME = source.name
    AND target.BREED = source.breed
    AND target.AGE = source.age
)
WHEN NOT MATCHED THEN
    INSERT (NAME, BREED, AGE)
    VALUES (source.name, source.breed, source.age);
